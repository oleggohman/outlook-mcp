#!/usr/bin/env python3
"""Generate hxprobe/src/props_gen.rs from schema/layout.json.

layout.json holds, per object type, its id, name, fields_end, ci_count,
fixed_len and one [ci, pid, name, offset, size, dt, child_type] row per
property. Offsets are item offsets (the 0x78-byte header included); -1 marks
a boolean stored as bit ci of bitmap A at fields_end. The output holds one
static `Prop` array per object type, one `p(...)` call per property in ci
order (`#[rustfmt::skip]` keeps them on one line each), and `TYPES`, all
type schemas sorted by type id. Lookup code and tests live in props.rs, so
regenerating never loses code.

Usage: python3 tools/gen_props.py <schema/layout.json> <hxprobe/src/props_gen.rs>
       (then run `cargo fmt` in hxprobe/)
"""
import json
import re
import sys

HEAD = """\
// @generated by tools/gen_props.py from schema/layout.json. Do not edit by
// hand: change the generator or the JSON and rerun it.

//! Property layout of every object type with a schema
//! (Outlook for Mac {outlook}).

use crate::props::{{p, Prop, TypeSchema}};

/// Number of object types in [`TYPES`].
pub const TYPE_COUNT: usize = {count};
"""

IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")


def static_name(type_name):
    # MessageHeader -> MESSAGE_HEADER_PROPS
    snake = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", type_name)
    return snake.upper() + "_PROPS"


def check(cond, msg):
    if not cond:
        raise SystemExit(msg)


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    with open(sys.argv[1], encoding="utf-8") as f:
        doc = json.load(f)
    types = doc["types"]
    ids = [t["id"] for t in types]
    check(ids == sorted(set(ids)), "types are not strictly sorted by id")

    out = [HEAD.format(outlook=doc["source"]["outlook"], count=len(types))]
    statics = set()
    lowered = set()
    entries = []
    for t in types:
        name = t["name"]
        check(IDENT.match(name) is not None, f"unexpected type name {name!r}")
        check(0 <= t["id"] <= 0xFFFF, f"{name}: id does not fit u16")
        check(0 <= t["ci_count"] <= 0xFFFF, f"{name}: ci_count does not fit u16")
        # SQLite table names are case-insensitive.
        check(name.lower() not in lowered, f"type names differ only by case: {name}")
        lowered.add(name.lower())
        sname = static_name(name)
        check(sname not in statics, f"static name clash: {sname}")
        statics.add(sname)
        lines = []
        for ci, pid, pname, off, size, dt, child in t["props"]:
            check(pname == "" or IDENT.match(pname) is not None,
                  f"{name}: unexpected property name {pname!r}")
            check(0 <= ci <= 0xFFFF and 0 <= pid <= 0xFFFF and 0 <= child <= 0xFFFF,
                  f"{name}: ci/pid/child_type out of u16 range")
            check(0 <= size <= 0xFF and 0 <= dt <= 0xFF, f"{name}: size/dt out of u8 range")
            check(off == -1 or 0 <= off <= 0x7FFFFFFF, f"{name}: bad offset {off}")
            off_s = "-1" if off == -1 else f"0x{off:x}"
            lines.append(f'    p({ci}, {pid}, "{pname}", {off_s}, {size}, 0x{dt:x}, {child}),\n')
        # rustfmt would split long calls; keep one property per line.
        out.append(f"\n#[rustfmt::skip]\nstatic {sname}: [Prop; {len(lines)}] = [\n")
        out.extend(lines)
        out.append("];\n")
        entries.append(
            "    TypeSchema {\n"
            f"        type_id: 0x{t['id']:x},\n"
            f'        name: "{name}",\n'
            f"        fields_end: 0x{t['fields_end']:x},\n"
            f"        ci_count: {t['ci_count']},\n"
            f"        fixed_len: 0x{t['fixed_len']:x},\n"
            f"        props: &{sname},\n"
            "    },\n"
        )
    out.append("\n/// Every type schema, strictly sorted by type id.\n")
    out.append("pub static TYPES: [TypeSchema; TYPE_COUNT] = [\n")
    out.extend(entries)
    out.append("];\n")
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write("".join(out))
    print(f"wrote {sys.argv[2]}: {len(types)} types, "
          f"{sum(len(t['props']) for t in types)} props")


if __name__ == "__main__":
    main()
